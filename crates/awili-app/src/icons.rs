#[cfg(test)]
mod tests {
    use super::*;

    /// Every enum variant resolves through the AssetSource to embedded bytes
    /// that honor the stroke-icon contract. The macro makes half-registration
    /// impossible, and iterating [`Icon::ALL`] makes this exhaustive by
    /// construction.
    #[test]
    fn icon_assets_all_resolve() {
        for ic in Icon::ALL {
            let bytes = Assets
                .load(ic.path())
                .expect("load never errors")
                .unwrap_or_else(|| panic!("{ic:?} ({}) missing from Assets", ic.path()));
            let text = std::str::from_utf8(&bytes).expect("svg is utf-8");
            assert!(text.starts_with("<svg"), "{ic:?} is not an svg document");
            for clause in [
                "viewBox=\"0 0 24 24\"",
                "fill=\"none\"",
                "stroke-width=\"2\"",
                "stroke-linecap=\"round\"",
                "stroke-linejoin=\"round\"",
            ] {
                assert!(text.contains(clause), "{ic:?} violates contract: {clause}");
            }
        }
    }

    /// The file-extension mapping stays total and case-insensitive.
    #[test]
    fn extension_mapping() {
        assert_eq!(Icon::for_extension("rs"), Icon::FileCode);
        assert_eq!(Icon::for_extension("PNG"), Icon::Image);
        assert_eq!(Icon::for_extension("xlsx"), Icon::BarChart);
        assert_eq!(Icon::for_extension("pptx"), Icon::FileText);
        assert_eq!(Icon::for_extension("toml"), Icon::Gear);
        assert_eq!(Icon::for_extension("weird"), Icon::File);
    }

    /// The color-emoji ban, mechanically enforced (review finding: the rule
    /// had no gate, and drift was observed during the branch itself). Walks
    /// every source file in this crate and fails on emoji-presentation
    /// scalars or the FE0F variation selector outside the allowlist.
    /// `composer.rs` is allowlisted: its emoji fixtures test UTF-16 offset math.
    #[test]
    fn no_color_emoji_in_chrome_sources() {
        let src_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let allow = ["composer.rs"];
        let mut checked = 0usize;
        for entry in std::fs::read_dir(&src_dir).expect("src dir") {
            let path = entry.expect("dir entry").path();
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            let name = path.file_name().unwrap().to_string_lossy().to_string();
            if allow.contains(&name.as_str()) {
                continue;
            }
            let text = std::fs::read_to_string(&path).expect("read source");
            for (i, ch) in text.char_indices() {
                let cp = ch as u32;
                let banned = cp == 0xFE0F || (0x1F000..=0x1FAFF).contains(&cp);
                assert!(
                    !banned,
                    "{name}: banned emoji scalar U+{cp:04X} at byte {i} — \
                     interactive chrome must use icons::Icon"
                );
            }
            checked += 1;
        }
        assert!(checked > 10, "scan looked at too few files ({checked})");
    }
}

impl Icon {
    /// The wireframe icon for a file, by extension (case-insensitive). One
    /// neutral vocabulary for every file listing in the app.
    pub fn for_extension(ext: &str) -> Icon {
        match ext.to_ascii_lowercase().as_str() {
            "png" | "jpg" | "jpeg" | "gif" | "svg" | "webp" => Icon::Image,
            "zip" | "tar" | "gz" | "7z" => Icon::Package,
            "xlsx" | "xls" | "csv" => Icon::BarChart,
            "pptx" | "ppt" | "pdf" | "docx" | "doc" | "md" | "txt" => Icon::FileText,
            "rs" | "ts" | "tsx" | "js" | "jsx" | "py" | "css" | "scss" | "html" | "sh" | "bash"
            | "zsh" => Icon::FileCode,
            "toml" | "yaml" | "yml" | "json" => Icon::Gear,
            _ => Icon::File,
        }
    }
}

/// Compile-time embedded assets for gpui (`svg()` needs an [`AssetSource`]).
pub struct Assets;

impl AssetSource for Assets {
    fn load(&self, path: &str) -> gpui::Result<Option<Cow<'static, [u8]>>> {
        Ok(Icon::ALL
            .iter()
            .find(|ic| ic.path() == path)
            .map(|ic| Cow::Borrowed(ic.bytes())))
    }

    fn list(&self, _path: &str) -> gpui::Result<Vec<SharedString>> {
        Ok(Vec::new())
    }
}

/// A sized, tinted icon element. `size` is an unscaled px value — it goes
/// through [`theme::z`] like every other dimension, so interface zoom scales
/// icons with the layout.
pub fn icon(which: Icon, size: f32, color: Rgba) -> Svg {
    svg()
        .path(which.path())
        .size(theme::z(size))
        .text_color(color)
        .flex_none()
}

/// The tooltip view behind [`tip`]: one small raised chip carrying the
/// control's text label. Deliberately minimal — a label, not a paragraph.
struct IconTip {
    label: SharedString,
}

impl Render for IconTip {
    fn render(&mut self, _window: &mut Window, _cx: &mut Context<Self>) -> impl IntoElement {
        // Test-only: a paint-time recorder. GPUI lays out (renders) a
        // tooltip candidate before deciding to show it, but paints only the
        // one it shows — so the label is recorded at paint.
        #[cfg(test)]
        let recorder = {
            let label = self.label.clone();
            gpui::canvas(
                |_, _, _| (),
                move |_, _, _, _| SHOWN_TIP.with(|t| *t.borrow_mut() = Some(label.clone())),
            )
            .absolute()
            .size_0()
        };
        #[cfg(not(test))]
        let recorder = gpui::Empty;
        div()
            .relative()
            .child(recorder)
            .px(theme::z(8.))
            .py(theme::z(3.))
            .rounded(theme::z(theme::RADIUS))
            .bg(theme::p().raised)
            .border_1()
            .border_color(theme::p().border)
            .text_size(theme::z(theme::LABEL_SIZE))
            .text_color(theme::p().text)
            .child(self.label.clone())
    }
}

/// A tooltip builder: after gpui's hover delay (500ms) a small chip pops up
/// with `label`. Usage: `.tooltip(icons::tip("Archive"))` on any stateful
/// element. Policy (per the 2026-08-23 review consensus): icon-only controls
/// MUST carry their text label; labeled controls carry a tip only when it is
/// ADDITIVE — a consequence, a shortcut, or a disambiguation — never an echo
/// of the label. Stateful controls describe the NEXT action.
pub fn tip(label: impl Into<SharedString>) -> impl Fn(&mut Window, &mut App) -> AnyView + 'static {
    let label = label.into();
    move |_window, cx| {
        let label = label.clone();
        cx.new(|_| IconTip { label }).into()
    }
}

#[cfg(test)]
thread_local! {
    static SHOWN_TIP: std::cell::RefCell<Option<SharedString>> =
        const { std::cell::RefCell::new(None) };
}

/// Test-only: the label of the last tooltip GPUI actually drew, and clear
/// it.
#[cfg(test)]
pub(crate) fn take_shown_tip() -> Option<SharedString> {
    SHOWN_TIP.with(|t| t.borrow_mut().take())
}


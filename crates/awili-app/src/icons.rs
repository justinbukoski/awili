//! Hollow wireframe icon set — the app's ONLY icon language for interactive
//! controls.
//!
//! Design rule (Owner, 2026-08-23; refined by the Codex/GLM review the same
//! day): no color-emoji images anywhere in the chrome, and every INTERACTIVE
//! control's face is a stroke-only SVG (fill="none", stroke-width 2,
//! feather/lucide style, MIT) rendered by gpui as a tinted alpha mask.
//! Passive STATUS text may still use monochrome line glyphs (✓ ✗ ● ○ ◉ ▸ ▾ ⚠)
//! where they read as characters, not images. Icons take exactly the color
//! the view gives them via `text_color` — same discipline as text, same
//! tokens from [`crate::theme`]; muted by default, accent only when the thing
//! they mark deserves attention.
//!
//! The SVGs are embedded at compile time by [`Assets`] (registered on the
//! `Application` in `main`), so the binary stays self-contained.
//!
//! The whole inventory — enum, asset path, embedded bytes, and the `ALL`
//! slice the tests iterate — is generated by ONE macro invocation, so a new
//! icon cannot be half-registered (review finding: three hand-synchronized
//! lists could drift and ship a blank glyph).

use std::borrow::Cow;
use std::time::Duration;

use gpui::{
    div, svg, AnyView, App, AppContext as _, AssetSource, Context, IntoElement, ParentElement,
    Render, Rgba, SharedString, Styled, Svg, Window,
};

use crate::theme;

/// One macro generates the enum, `ALL`, `path()`, and the byte table —
/// adding an icon is exactly one line here plus the SVG file.
macro_rules! icon_set {
    ($(($variant:ident, $name:literal),)*) => {
        /// Every icon the app may draw.
        #[derive(Copy, Clone, Debug, PartialEq, Eq)]
        pub enum Icon {
            $($variant,)*
        }

        impl Icon {
            /// Every variant, for exhaustive tests and tooling.
            pub const ALL: &'static [Icon] = &[$(Icon::$variant,)*];

            /// The asset path gpui resolves through [`Assets`].
            pub fn path(self) -> &'static str {
                match self {
                    $(Icon::$variant => concat!("icons/", $name, ".svg"),)*
                }
            }

            /// The embedded SVG bytes for this icon.
            fn bytes(self) -> &'static [u8] {
                match self {
                    $(Icon::$variant =>
                        &include_bytes!(concat!("../assets/icons/", $name, ".svg"))[..],)*
                }
            }
        }
    };
}

